import { writeFileSync } from "node:fs";
import { allScenarios } from "../src/content";
import { personas } from "../src/content/data/personas";
import { TAGS } from "../src/content/data/beats";
import { lengthBias } from "../src/content/stats";
import { validateScenario } from "../src/engine/validate";

const count = <T>(items: T[], key: (x: T) => string) => {
  const m = new Map<string, number>();
  for (const i of items) m.set(key(i), (m.get(key(i)) ?? 0) + 1);
  return m;
};
const table = (head: string[], rows: (string | number)[][]) =>
  [`| ${head.join(" | ")} |`, `|${head.map(() => "---").join("|")}|`, ...rows.map((r) => `| ${r.join(" | ")} |`)].join("\n");

const LEVEL_NAME = ["", "Стажёр", "Новичок", "Практик", "Профи", "Акула"];
const reports = allScenarios.map((s) => ({ s, r: validateScenario(s) }));
const failed = reports.filter((x) => x.r.issues.some((i) => i.severity === "error"));

const byLevel = count(allScenarios, (s) => String(s.level));
const byNiche = count(allScenarios, (s) => s.niche);
const byChannel = count(allScenarios, (s) => s.channel);
const byPersona = count(allScenarios, (s) => s.persona.id);
const byTag = count(allScenarios.flatMap((s) => s.objectionTags.map((t) => ({ t }))), (x) => x.t);

const simRows = [1, 2, 3, 4, 5].map((lv) => {
  const rs = reports.filter((x) => x.s.level === lv && x.r.stats);
  const avg = (f: (x: NonNullable<(typeof rs)[0]["r"]["stats"]>) => number) => rs.reduce((a, x) => a + f(x.r.stats!), 0) / Math.max(1, rs.length);
  return [`${lv} · ${LEVEL_NAME[lv]}`, rs.length, `${(avg((x) => x.sale) * 100).toFixed(1)}%`, `${(avg((x) => x.partial) * 100).toFixed(1)}%`, `${(avg((x) => x.lost) * 100).toFixed(1)}%`, avg((x) => x.avgTurns).toFixed(1)];
});

const nodeCounts = allScenarios.map((s) => Object.keys(s.nodes).length);
const bias = lengthBias(allScenarios);

const md = `# CONTENT REPORT

Generated by \`npm run report\`. Do not edit by hand.

- Cases: **${allScenarios.length}** (target 100) · Personas: **${personas.length}** (target ≥ 20) · Validation: **${allScenarios.length - failed.length}/${allScenarios.length}** pass
- Nodes per case: min ${Math.min(...nodeCounts)}, max ${Math.max(...nodeCounts)}, avg ${(nodeCounts.reduce((a, b) => a + b, 0) / nodeCounts.length).toFixed(1)} (target ≥ 15)
- Length bias: the longest answer is the best (excellent) one in **${(bias.longestIsBest * 100).toFixed(0)}%** of client nodes (random would be ~25%); the shortest answer is the best in ${(bias.shortestIsBest * 100).toFixed(0)}%.

## By level
${table(["Level", "Cases", "Target"], [1, 2, 3, 4, 5].map((l) => [`${l} · ${LEVEL_NAME[l]}`, byLevel.get(String(l)) ?? 0, [24, 24, 20, 18, 14][l - 1]]))}

## Random-player simulation (1000 runs per case, average per level)
Rules: level 1 ≥ 30% sale, levels 4–5 ≤ 5% sale.

${table(["Level", "Cases", "Sale", "Partial", "Lost", "Avg turns"], simRows)}

## By niche
${table(["Niche", "Cases"], [...byNiche].map(([k, v]) => [k, v]))}

## By channel
${table(["Channel", "Cases"], [...byChannel].map(([k, v]) => [k, v]))}

## Objection tags (every taxonomy tag must appear)
${table(["Tag", "Cases"], TAGS.map((t) => [t, byTag.get(t) ?? 0]))}

## Personas usage
${table(["Persona", "Psychotype", "Cases"], personas.map((p) => [`${p.name}, ${p.age}, ${p.profession}`, p.psychotype, byPersona.get(p.id) ?? 0]))}

## Cases
${table(["#", "Id", "Level", "Niche", "Channel", "Persona", "Tags", "Nodes", "Sale % (random)"], reports.map(({ s, r }, i) => [i + 1, s.id, s.level, s.niche, s.channel, s.persona.name, s.objectionTags.join(", "), Object.keys(s.nodes).length, r.stats ? (r.stats.sale * 100).toFixed(1) : "—"]))}

## MWR Life facts used (the only facts stated as true)
- Elite **$340** and Turbo **$590**; **$100** of each goes to the company, the rest (**$240** / **$490**) is credited as points to the Travel Advantage account.
- Monthly subscription **$120**.
- Income only from building a distributor network; no income, payback, refund or discount is ever promised. Unknown terms (refunds, what the subscription includes, commissions) are answered with "check the contract and show it in writing".
- **Verify these facts against the official materials before using the trainer with a team.** They live in \`src/content/data/mwr.ts\`; the content tests fail if any other dollar amount appears.

## Known limits (honest notes)
- 99 of 100 cases are **assembled by a builder** (\`src/content/builder.ts\`) from personas, niche vocabularies and an objection bank (\`src/content/data/beats.ts\`). Graphs, flags, endings and calibration are real and validated, but client phrasing repeats across cases. Only \`mwr-l3-irina-accountant\` is hand-written.
- Next quality step: run the LLM pipeline from the master prompt (\`scripts/generate-scenarios.ts\`) to rewrite client lines per persona. The validator is already in place to gate that output.
- Level 4–5 "false facts" and the decision timer are not implemented as mechanics; level 5 only carries a warning in the debrief text.
`;
writeFileSync("CONTENT_REPORT.md", md, "utf-8");
console.log(`CONTENT_REPORT.md written (${allScenarios.length} cases, ${failed.length} failing)`);
process.exit(failed.length ? 1 : 0);
